    private static readonly List<string> outcomes = [];
    private static void Check(bool value, string label)
    { if (!value) throw new Exception(label); outcomes.Add("PASS " + label); }
    private static void Near(double actual, double expected, string label) => Check(Math.Abs(actual - expected) < Math.Max(1e-12, Math.Abs(expected) * 2e-13), label);
    [STAThread] private static int Main(string[] args)
    {
        string output = Path.GetFullPath(args[0]); Directory.CreateDirectory(output);
        try { if (args.Contains("--ui")) Ui(output); else Domain(); }
        catch (Exception ex) { outcomes.Add("FAIL " + ex); }
        File.WriteAllLines(Path.Combine(output, "esito.txt"), outcomes);
        foreach (string line in outcomes) Console.WriteLine(line);
        return outcomes.Any(x => x.StartsWith("FAIL")) ? 1 : 0;
    }
    private static void Domain()
    {
        var model = new ConcreteTimeEffectsViewModel(25) { Humidity = "50", NotionalSize = "200", LoadingAge = "7" };
        Check(!model.HasResults && model.Points.Count == 0 && model.InfinityText == "—", "input edit clears derived state");
        model.CalculateCommand.Execute(null);
        Check(model.HasResults && model.Error == "", "valid input is evaluated");
        // Independent Python reference frozen in Model/tests/Fixtures/concrete-time-effects.json (94efc9bc).
        // Constants are not generated by the UI or by the implementation under test.
        Near(model.CreepInfinity!.Value, 3.4427042104754673, "independent phi-infinity");
        foreach (var (age, phi, e, factor) in new[] {
            (0.5, 0d, 19355.383268685524, .61492891205196),
            (7d, 0d, 29201.47418828526, .9277434863285529),
            (17d, 1.0290493772315557, 30813.898916456557, .9789709185160731),
            (28d, 1.2781084754333878, 31475.806210019346, 1d),
            (365d, 2.6039611014981867, 33229.7796390431, 1.0557244957387442) })
        {
            model.QueryAge = age.ToString(CultureInfo.InvariantCulture);
            Near(model.QueryPoint!.CreepCoefficient, phi, "phi at " + age); Near(model.QueryPoint.EcmMpa, e, "E at " + age); Near(model.QueryPoint.ModulusFactor, factor, "factor at " + age);
        }
        Check(model.Points.Any(p => p.AgeDays == 7) && model.Points.Any(p => p.AgeDays == 28), "loading and 28-day samples included exactly");
        Check(model.Points.Zip(model.Points.Skip(1)).All(p => p.First.AgeDays < p.Second.AgeDays), "time samples strictly ordered without duplicates");
        Check(model.Points.First().AgeDays >= .5 && model.Points.Last().AgeDays <= 10000, "samples remain inside requested interval");
        var original = model.Points; model.LogX = false; model.LogY = true; model.SelectedCurve = model.Curves[2];
        Check(ReferenceEquals(original, model.Points), "graph choices do not change calculated data");
        model.SelectedPoint = model.Points.First(p => p.AgeDays == 28);
        Check(model.QueryPoint?.AgeDays == 28 && model.QueryFactorText == "1,000", "table selection updates precise reading and Italian display");
        foreach (string bad in new[] { "", "NaN", "Infinity", "0", "-2", "abc", "1.2.3" })
        {
            model.QueryAge = bad; Check(model.QueryPoint is null && model.QueryError.Length > 0 && model.HasResults, "invalid reading does not erase curve: " + bad);
        }
        model.QueryAge = "17,0"; Near(model.QueryPoint!.CreepCoefficient, 1.0290493772315557, "decimal comma accepted");
        foreach (var (property, bad) in new[] { ("Fck", "11"), ("Humidity", "101"), ("NotionalSize", "0"), ("LoadingAge", "0.49"), ("StartAge", "0"), ("EndAge", "0.1"), ("Samples", "30.5"), ("Samples", "1001"), ("Fck", "NaN"), ("Humidity", "1.2.3") })
        {
            var vm = new ConcreteTimeEffectsViewModel(); typeof(ConcreteTimeEffectsViewModel).GetProperty(property)!.SetValue(vm, bad);
            Check(!vm.HasResults && vm.Points.Count == 0 && vm.QueryPoint is null, "stale results cleared for " + property + "=" + bad);
            vm.CalculateCommand.Execute(null);
            Check(!vm.HasResults && ((IDataErrorInfo)vm)[property].Length > 0 && vm.Status.Length > 0, "visible rejection for " + property + "=" + bad);
        }
        model.Fck = "35"; model.CalculateCommand.Execute(null); Check(model.HasResults, "recovery after edit");
        double normal = model.CreepInfinity!.Value;
        foreach (var cement in model.Cements) { model.Cement = cement; model.CalculateCommand.Execute(null); Check(model.HasResults && double.IsFinite(model.CreepInfinity!.Value), "cement " + cement.Label); }
        Check(model.CreepInfinity != normal, "cement selection reaches domain API");
        var names = typeof(ConcreteTimeEffectsViewModel).Assembly.GetReferencedAssemblies().Select(a => a.Name).ToArray();
        Check(!names.Any(n => n is "PresentationCore" or "PresentationFramework" or "WindowsBase"), "ViewModel assembly has no WPF dependency");
    }
    private static IEnumerable<T> Children<T>(DependencyObject parent) where T : DependencyObject
    {
        for (int i = 0; i < VisualTreeHelper.GetChildrenCount(parent); i++)
        { var child = VisualTreeHelper.GetChild(parent, i); if (child is T t) yield return t; foreach (var d in Children<T>(child)) yield return d; }
    }
    private static void Pump() => Dispatcher.CurrentDispatcher.Invoke(() => { }, DispatcherPriority.ApplicationIdle);
    private static void Ui(string output)
    {
        RenderOptions.ProcessRenderMode = System.Windows.Interop.RenderMode.SoftwareOnly;
        var app = new Application { ShutdownMode = ShutdownMode.OnExplicitShutdown }; Anthea.Desktop.Testing.WpfTestResources.Load(app);
        var assembly = typeof(X.Desktop.MainWindow).Assembly;
        var appearance = assembly.GetType("X.Desktop.Appearance")!;
        appearance.GetMethod("Initialize", Statics)!.Invoke(null, [false]);
        var viewType = assembly.GetType("X.Desktop.ConcreteTimeEffectsView")!;
        var model = new ConcreteTimeEffectsViewModel();
        var view = (FrameworkElement)Activator.CreateInstance(viewType, Members, null, [model], null)!;
        var window = new Window { Content = view, Width = 1320, Height = 880, Left = -10000, Top = -10000, ShowActivated = false, ShowInTaskbar = false };
        appearance.GetMethod("Watch", Statics)!.Invoke(null, [window]);
        try
        {
            window.Show(); Pump();
            foreach (string mode in new[] { "Light", "Dark", "VeryDark" })
            {
                appearance.GetMethod("Set", Statics)!.Invoke(null, [Enum.Parse(assembly.GetType("X.Desktop.AppAppearance")!, mode), false]); Pump();
                Check(Children<TextBlock>(view).Any(t => t.Text == model.InfinityText), mode + ": phi-infinity bound");
                Check(Children<TextBlock>(view).Any(t => t.Text == model.QueryEText), mode + ": query modulus bound");
                Capture(view, Path.Combine(output, "reologia-" + mode.ToLowerInvariant() + ".png"));
                var plot = (FrameworkElement)viewType.GetField("plot", Members)!.GetValue(view)!;
                var position = plot.TransformToAncestor(view).Transform(new Point(2, 2));
                var pixels = Bitmap(view); var pixel = new byte[4]; pixels.CopyPixels(new Int32Rect((int)position.X, (int)position.Y, 1, 1), pixel, 4, 0);
                Check(mode == "Light" ? pixel[0] > 240 : pixel[0] < 80, mode + ": plot uses theme background");
                var tabs = Children<TabControl>(view).Single(); tabs.SelectedIndex = 1; Pump();
                var table = Children<DataGrid>(view).Single(); Check(table.Items.Count == model.Points.Count, mode + ": table uses the same result snapshot");
                table.SelectedItem = model.Points.First(p => p.AgeDays == 28); Pump();
                Check(model.QueryPoint?.AgeDays == 28, mode + ": table selection binding");
                Capture(view, Path.Combine(output, "tabella-" + mode.ToLowerInvariant() + ".png")); tabs.SelectedIndex = 0; Pump();
            }
            var fck = Children<TextBox>(view).Single(b => BindingOperations.GetBinding(b, TextBox.TextProperty)?.Path.Path == nameof(model.Fck));
            fck.Text = "bad"; Pump(); Check(!model.HasResults && model.Points.Count == 0, "editing WPF text clears stale plot");
            var calculate = Children<Button>(view).Single(b => b.Content?.ToString() == "Aggiorna le curve");
            calculate.Command.Execute(null); Pump(); Check(Validation.GetHasError(fck) && !model.HasResults, "field validation appears after command");
            fck.Text = "30"; calculate.Command.Execute(null); Pump(); Check(model.HasResults && !Validation.GetHasError(fck), "WPF recovery after correcting input");
            model.LogY = true; Pump(); Check(model.Points.Any(p => p.CreepCoefficient == 0), "log plot preserves zero values in table");
            model.SelectedCurve = model.Curves[1]; Pump(); Capture(view, Path.Combine(output, "modulo-log.png"));
            window.Width = 1050; window.Height = 740; Pump(); Capture(view, Path.Combine(output, "reologia-compatta.png"));
            Check(view.ActualWidth >= 1000 && view.ActualHeight > 650, "compact window remains laid out");
            var plotObject = viewType.GetField("plot", Members)!.GetValue(view)!;
            byte[] png = (byte[])plotObject.GetType().BaseType!.GetMethod("Png", Members)!.Invoke(plotObject, [1200, 750])!;
            File.WriteAllBytes(Path.Combine(output, "grafico-esportato.png"), png); Check(png.Length > 10000, "existing PNG exporter reused");
        }
        finally { window.Close(); app.Shutdown(); }
    }
    private static RenderTargetBitmap Bitmap(FrameworkElement element)
    {
        element.UpdateLayout(); var bitmap = new RenderTargetBitmap((int)Math.Ceiling(element.ActualWidth), (int)Math.Ceiling(element.ActualHeight), 96, 96, PixelFormats.Pbgra32); bitmap.Render(element); return bitmap;
    }
    private static void Capture(FrameworkElement view, string path)
    { var encoder = new PngBitmapEncoder(); encoder.Frames.Add(BitmapFrame.Create(Bitmap(view))); using var stream = File.Create(path); encoder.Save(stream); }
